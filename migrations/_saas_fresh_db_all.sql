-- 회사는 자기 행만 본다. 요금제·기간은 서버(service role)만 바꾼다 — 아래 트리거가 막는다.
drop policy if exists company_accounts_select on company_accounts;
create policy company_accounts_select on company_accounts for select using (owner_id = auth.uid());
drop policy if exists company_accounts_update on company_accounts;
create policy company_accounts_update on company_accounts for update using (owner_id = auth.uid()) with check (owner_id = auth.uid());
drop policy if exists subscription_events_select on subscription_events;
create policy subscription_events_select on subscription_events for select using (owner_id = auth.uid());

-- 브라우저(auth.uid() 가 있는 요청)는 이름·연락처만 고칠 수 있다. 요금제·기간·아이디는 service role 전용.
create or replace function company_accounts_guard() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  if auth.uid() is not null then
    if new.owner_id <> old.owner_id or new.login_id <> old.login_id or new.plan <> old.plan or new.status <> old.status
       or new.trial_end <> old.trial_end or new.current_period_end is distinct from old.current_period_end
       or new.max_managers <> old.max_managers then
      raise exception 'company_accounts: 요금제·기간·아이디는 화면에서 바꿀 수 없습니다' using errcode = '42501';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists company_accounts_guard on company_accounts;
create trigger company_accounts_guard before update on company_accounts for each row execute function company_accounts_guard();

-- ── 2. 구독 활성 판정 ─────────────────────────────────────────
-- 행이 없으면(사내 계정·가입 전 이식 데이터) 참. 체험: trial_end 전. 유료: current_period_end + 3일 유예 전.
-- status 가 canceled 면 거짓. past_due 는 유예 안이면 참.
create or replace function is_company_active() returns boolean
language sql stable security definer set search_path = public, extensions as $$
  select coalesce((
    select case
      when a.status = 'canceled' then false
      when a.plan = 'trial' then a.trial_end > now()
      else coalesce(a.current_period_end, 'infinity'::timestamptz) + interval '3 days' > now()
    end
    from company_accounts a where a.owner_id = auth.uid()
  ), true)
$$;
grant execute on function is_company_active() to authenticated, anon;

-- ── 3. 담당자 PIN ─────────────────────────────────────────────
create table if not exists manager_pins (
  manager_id bigint primary key references managers(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  pin_hash text not null,
  fail_count int not null default 0,
  locked_until timestamptz,
  updated_at timestamptz not null default now()
);
create index if not exists idx_manager_pins_user on manager_pins(user_id);
alter table manager_pins enable row level security;
-- 정책을 하나도 두지 않는다 → anon/authenticated 는 읽기·쓰기 모두 불가. 아래 security definer 함수만 접근.

-- 잠금 규칙: 5회 틀리면 10분. 4자리(10,000 조합)는 이 잠금이 없으면 의미가 없다.
create or replace function manager_pin_status() returns jsonb
language sql stable security definer set search_path = public, extensions as $$
  select coalesce(jsonb_agg(jsonb_build_object(
      'manager_id', m.id,
      'has_pin', p.manager_id is not null,
      'locked_until', case when p.locked_until > now() then p.locked_until end
    ) order by m.id), '[]'::jsonb)
  from managers m left join manager_pins p on p.manager_id = m.id
  where m.user_id = auth.uid()
$$;
grant execute on function manager_pin_status() to authenticated;

create or replace function verify_manager_pin(p_manager_id bigint, p_pin text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  r manager_pins%rowtype;
  own uuid;
begin
  select user_id into own from managers where id = p_manager_id;
  if own is null or own <> auth.uid() then
    return jsonb_build_object('ok', false, 'error', '담당자를 찾을 수 없습니다');
  end if;
  select * into r from manager_pins where manager_id = p_manager_id for update;
  if not found then
    return jsonb_build_object('ok', false, 'no_pin', true);
  end if;
  if r.locked_until is not null and r.locked_until > now() then
    return jsonb_build_object('ok', false, 'locked_until', r.locked_until);
  end if;
  if p_pin is not null and p_pin ~ '^\d{4}$' and r.pin_hash = crypt(p_pin, r.pin_hash) then
    update manager_pins set fail_count = 0, locked_until = null where manager_id = p_manager_id;
    return jsonb_build_object('ok', true);
  end if;
  if r.fail_count + 1 >= 5 then
    update manager_pins set fail_count = 0, locked_until = now() + interval '10 minutes' where manager_id = p_manager_id;
    return jsonb_build_object('ok', false, 'locked_until', now() + interval '10 minutes');
  end if;
  update manager_pins set fail_count = fail_count + 1 where manager_id = p_manager_id;
  return jsonb_build_object('ok', false, 'attempts_left', 5 - (r.fail_count + 1));
end $$;
grant execute on function verify_manager_pin(bigint, text) to authenticated;

-- PIN 설정/변경.
--   · 아직 PIN 이 없는 담당자: 회사 세션만 있으면 누구나 처음 PIN 을 만들 수 있다(가입 직후 온보딩).
--   · 이미 있으면: 본인이 현재 PIN 을 맞추거나, 관리자(is_admin) 담당자가 자기 PIN 을 맞춰야 바꿀 수 있다.
--   p_by_manager_id / p_by_pin 이 그 증명이다.
create or replace function set_manager_pin(p_manager_id bigint, p_pin text, p_by_manager_id bigint default null, p_by_pin text default null) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare
  own uuid;
  has_pin boolean;
  by_admin boolean;
  v jsonb;
begin
  if p_pin is null or p_pin !~ '^\d{4}$' then
    return jsonb_build_object('ok', false, 'error', 'PIN 은 숫자 4자리여야 합니다');
  end if;
  select user_id into own from managers where id = p_manager_id;
  if own is null or own <> auth.uid() then
    return jsonb_build_object('ok', false, 'error', '담당자를 찾을 수 없습니다');
  end if;
  select exists(select 1 from manager_pins where manager_id = p_manager_id) into has_pin;
  if has_pin then
    if p_by_manager_id is null then
      return jsonb_build_object('ok', false, 'error', '현재 PIN 확인이 필요합니다');
    end if;
    select coalesce(is_admin, false) into by_admin from managers where id = p_by_manager_id and user_id = auth.uid();
    if by_admin is null then
      return jsonb_build_object('ok', false, 'error', '확인하는 담당자를 찾을 수 없습니다');
    end if;
    if p_by_manager_id <> p_manager_id and not by_admin then
      return jsonb_build_object('ok', false, 'error', '다른 담당자의 PIN 은 관리자만 바꿀 수 있습니다');
    end if;
    v := verify_manager_pin(p_by_manager_id, p_by_pin);
    if not (v->>'ok')::boolean then
      return jsonb_build_object('ok', false, 'error', '확인 PIN 이 맞지 않습니다', 'verify', v);
    end if;
  end if;
  insert into manager_pins (manager_id, user_id, pin_hash, fail_count, locked_until, updated_at)
  values (p_manager_id, own, crypt(p_pin, gen_salt('bf', 8)), 0, null, now())
  on conflict (manager_id) do update
    set pin_hash = excluded.pin_hash, fail_count = 0, locked_until = null, updated_at = now();
  return jsonb_build_object('ok', true);
end $$;
grant execute on function set_manager_pin(bigint, text, bigint, text) to authenticated;

-- 서버(service role) 전용 — 회사 비밀번호를 확인한 뒤 PIN 을 강제로 다시 놓는다(관리자가 PIN 을 잃었을 때).
-- auth.uid() 가 있는(브라우저) 요청은 거부한다.
create or replace function service_reset_manager_pin(p_owner_id uuid, p_manager_id bigint, p_pin text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
begin
  if auth.uid() is not null then
    return jsonb_build_object('ok', false, 'error', '서버 전용 함수입니다');
  end if;
  if p_pin is null or p_pin !~ '^\d{4}$' then
    return jsonb_build_object('ok', false, 'error', 'PIN 은 숫자 4자리여야 합니다');
  end if;
  if not exists (select 1 from managers where id = p_manager_id and user_id = p_owner_id) then
    return jsonb_build_object('ok', false, 'error', '담당자를 찾을 수 없습니다');
  end if;
  insert into manager_pins (manager_id, user_id, pin_hash, fail_count, locked_until, updated_at)
  values (p_manager_id, p_owner_id, crypt(p_pin, gen_salt('bf', 8)), 0, null, now())
  on conflict (manager_id) do update
    set pin_hash = excluded.pin_hash, fail_count = 0, locked_until = null, updated_at = now();
  return jsonb_build_object('ok', true);
end $$;
revoke execute on function service_reset_manager_pin(uuid, bigint, text) from public, anon, authenticated;
grant execute on function service_reset_manager_pin(uuid, bigint, text) to service_role;


