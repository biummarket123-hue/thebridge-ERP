-- 무슨 문제를 푸는가:
--   적립금 카드를 펼치면 담당자 메모만 보였다. 주문 차감·환불 전환처럼 주문에서 생긴 기록은
--   그 주문의 💬 메모(주문현황 카드에 보이는 것)를 같이 봐야 맥락이 잡히는데, credits 에는
--   주문 연결이 없어 찾을 길이 없었다. order_id 를 남겨 카드에서 주문 메모를 함께 보여준다.
--
--   order_id: 이 기록을 만든 주문(orders.id). 직접 적립·회수처럼 주문이 없으면 null.
--             주문이 지워져도 기록은 남아야 하므로 외래키는 걸지 않는다.

alter table credits add column if not exists order_id text;
