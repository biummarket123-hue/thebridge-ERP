-- 배송지 메모 프리셋 — 자주 쓰는 배송 메모를 기록해 재사용/검색/삭제
-- Supabase 대시보드 > SQL Editor 에서 한 번 실행하세요.
--
-- 주문 등록 시 입력한 배송 메모(delivery_message)를 이 테이블에도 upsert 하여
-- 다음 입력 때 자동완성 후보로 검색되게 함. 사용자가 개별 삭제 가능.

create table if not exists delivery_message_presets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  text text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- (user_id, text) 중복 방지 — 같은 메모는 한 줄만 유지, upsert로 updated_at 갱신
create unique index if not exists idx_delivery_presets_user_text on delivery_message_presets(user_id, text);
create index if not exists idx_delivery_presets_user on delivery_message_presets(user_id);

alter table delivery_message_presets enable row level security;

drop policy if exists tenant_delivery_presets on delivery_message_presets;
create policy tenant_delivery_presets on delivery_message_presets
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
