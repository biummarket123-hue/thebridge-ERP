-- 라벨 자동 출력 — 어느 주문의 라벨을 이미 뽑았는지 기록한다
-- Supabase 대시보드 > SQL Editor 에서 한 번 실행하세요. ⚠️ 배포보다 먼저 실행해야 합니다.
--
-- 무엇을 하는 기능인가:
--   직원들은 각자 PC·모바일에서 주문을 등록한다. 인쇄는 브라우저가 하는 일이라
--   등록한 사람의 기기에서만 인쇄창이 뜨는데, PS100 은 한 대에만 물려 있다.
--   그래서 PS100 이 붙은 PC 한 대가 ERP 를 켜둔 채 새 주문을 실시간으로 받아
--   대신 뽑는다. 등록하는 직원은 인쇄에 대해 아무것도 하지 않는다.
--
-- 왜 이 컬럼이 반드시 필요한가 — 이게 없으면 세 가지가 전부 깨진다:
--   1) 출력 PC 를 새로고침할 때마다 지난 주문이 통째로 다시 쏟아진다
--   2) 실수로 두 대를 출력 담당으로 켜두면 모든 라벨이 두 번 나온다
--   3) 잠깐 꺼졌다 켰을 때 어디까지 뽑았는지 알 방법이 없다
--
--   감열지는 되돌릴 수 없다. "혹시 몰라 한 번 더" 가 곧 버리는 종이다.
--
-- 왜 '뽑았다' 를 boolean 이 아니라 시각으로 두는가:
--   두 번 나왔다는 신고가 들어왔을 때 언제 뽑혔는지 봐야 원인을 가른다.
--   boolean 이면 "이미 true 였다" 밖에 안 남아 아무것도 못 가린다.

alter table orders add column if not exists label_printed_at timestamptz;

-- 출력 PC 가 매번 훑는 경로는 하나뿐이다: "아직 안 뽑은 것을 등록순으로".
-- 부분 인덱스라 이미 뽑은 주문(시간이 갈수록 대부분)은 아예 들어오지 않는다.
create index if not exists idx_orders_label_unprinted
  on orders (user_id, created_at)
  where label_printed_at is null;
