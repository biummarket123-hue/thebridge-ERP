insert into storage.buckets (id, name, public) values ('order-images', 'order-images', true) on conflict (id) do nothing;
drop policy if exists "order-images auth select" on storage.objects;
drop policy if exists "order-images auth insert" on storage.objects;
drop policy if exists "order-images auth delete" on storage.objects;
create policy "order-images auth select" on storage.objects for select to authenticated using (bucket_id = 'order-images');
create policy "order-images auth insert" on storage.objects for insert to authenticated with check (bucket_id = 'order-images');
create policy "order-images auth delete" on storage.objects for delete to authenticated using (bucket_id = 'order-images');
