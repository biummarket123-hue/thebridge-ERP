create extension if not exists pgcrypto;

-- ── 주문 ──────────────────────────────────────────────────────
create table if not exists orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  date text, time text,
  customer text, phone text,
  items jsonb default '[]',
  payment text default '미입금',
  address text, address_detail text,
  delivery_message text,
  links jsonb default '[]',
  note text, memo text,
  status text default '접수',
  manager text default '',
  total_amount numeric, shipping_fee numeric default 0, other_cost numeric,
  combined_payment boolean default false, combined_shipping boolean default false,
  deposit_amount numeric, balance_amount numeric,
  refund_amount numeric, refund_note text,
  payment_status text, sales_channel text,
  images jsonb default '[]',
  receipt_type text, receipt_issued boolean default false,
  free_shipping_used boolean not null default false,
  ship_date text, is_urgent boolean default false,
  courier text, shipped_via text,
  merge_group_id text, split_shipping boolean default false, shipping_fee_held numeric,
  packed_at timestamptz, packed_sig text,
  shipped_at timestamptz,
  is_holding boolean default false, held_at timestamptz,
  is_parked boolean default false, parked_at timestamptz, park_reason text,
  ship_requested_at timestamptz, ship_requested_by text,
  invoice_printed_at timestamptz,
  last_actor text, last_route text, last_actor_at timestamptz,
  created_at timestamptz default now()
);
create index if not exists idx_orders_user on orders(user_id);
create index if not exists idx_orders_user_status on orders(user_id, status);
create index if not exists idx_orders_user_created on orders(user_id, created_at desc);

-- ── 고객(거래처) ──────────────────────────────────────────────
create table if not exists customers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  name text not null,
  phone text default '',
  nickname text default '',
  address text default '',
  address_detail text default '',
  total_orders int default 0,
  last_order text,
  note text default '',
  created_at timestamptz default now()
);
create index if not exists idx_customers_user on customers(user_id);

-- ── 재고(옛 수량 재고 — 롤 재고 products/stock_rolls 는 add_stock_rolls.sql) ──
create table if not exists inventory (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  fabric text not null,
  color text default '',
  stock numeric default 0,
  item_no text,
  unit_price numeric
);
create index if not exists idx_inventory_user on inventory(user_id);

-- ── 입출고 로그 ───────────────────────────────────────────────
create table if not exists logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  date text, time text,
  type text,
  item_no text default '',
  fabric text, color text default '',
  qty numeric default 0,
  cost_price numeric default 0,
  ref text default '',
  note text default '',
  customer text, manager text, status text, items jsonb,
  created_at timestamptz default now()
);
create index if not exists idx_logs_user on logs(user_id, created_at desc);

-- ── 담당자 ────────────────────────────────────────────────────
create table if not exists managers (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  name text not null,
  is_admin boolean not null default false,
  is_public boolean not null default false,
  is_packer boolean not null default false,
  code text
);
create unique index if not exists idx_managers_user_name on managers(user_id, name);

-- ── 설정(회사당 한 줄) ────────────────────────────────────────
create table if not exists settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz default now()
);

-- ── 계약금/잔금 ───────────────────────────────────────────────
create table if not exists deposits (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  customer text not null,
  phone text default '',
  content text default '',
  total bigint not null default 0,
  deposit bigint not null default 0,
  deposit_date text default '',
  balance_paid boolean not null default false,
  balance_date text default '',
  reg_date text default '',
  note text default '',
  created_at timestamptz default now()
);
create index if not exists idx_deposits_user on deposits(user_id);

-- ── 적립금 ────────────────────────────────────────────────────
create table if not exists credits (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  customer text not null,
  type text not null,
  amount numeric not null default 0,
  memo text,
  manager text,
  order_id text,
  created_at timestamptz default now()
);
create index if not exists idx_credits_user on credits(user_id, created_at desc);

-- ── 입금·환불 로그(정산) ──────────────────────────────────────
create table if not exists payment_logs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  order_id text,
  customer text,
  type text not null,
  amount numeric not null default 0,
  note text,
  code text,
  created_at timestamptz default now()
);
create index if not exists idx_payment_logs_user on payment_logs(user_id, created_at desc);

-- ── 무료배송권 ────────────────────────────────────────────────
-- order_id 는 text (db.js 가 글자로 비교) — orders.id(uuid) 에 FK 를 걸지 않는다.
create table if not exists free_shipping_coupons (
  id uuid primary key default gen_random_uuid(),
  customer text not null,
  count integer not null default 0,
  user_id uuid references auth.users(id) on delete cascade,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  unique(customer, user_id)
);
create table if not exists free_shipping_logs (
  id uuid primary key default gen_random_uuid(),
  customer text not null,
  type text not null check (type in ('issue', 'use', 'restore', 'cancel')),
  count integer not null,
  order_id text,
  user_id uuid references auth.users(id) on delete cascade,
  created_at timestamptz default now()
);
create index if not exists idx_fsc_user on free_shipping_coupons(user_id);
create index if not exists idx_fsl_user on free_shipping_logs(user_id, created_at desc);

-- ── RLS: 회사 격리 ────────────────────────────────────────────
do $$
declare t text;
begin
  foreach t in array array['orders','customers','inventory','logs','managers','settings','deposits','credits','payment_logs','free_shipping_coupons','free_shipping_logs'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists tenant_%I on %I', t, t);
    execute format('create policy tenant_%I on %I for all using (user_id = auth.uid()) with check (user_id = auth.uid())', t, t);
  end loop;
end $$;

-- ── Realtime(실시간 구독) ─────────────────────────────────────
do $$
declare t text;
begin
  foreach t in array array['orders','customers','credits','payment_logs','managers'] loop
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = t) then
      execute format('alter publication supabase_realtime add table %I', t);
    end if;
  end loop;
end $$;

