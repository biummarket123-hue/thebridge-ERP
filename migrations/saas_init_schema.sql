-- 지금 앱 코드(src/lib/db.js)가 기대하는 모양이 아니다. 이 파일은 db.js 가 실제로 읽고 쓰는 칸으로
-- 기본 표를 만들고, 처음부터 회사 격리(user_id = auth.uid())를 건다. 이어서 migrations/ 의 기능별 파일을
-- docs/saas-db-setup.md 의 순서대로 실행한다(tests/saas/test-fresh-db.mjs 가 그 순서를 PGlite 로 검증한다).
