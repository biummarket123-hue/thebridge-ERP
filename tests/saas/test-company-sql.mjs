// 구독형 SaaS 마이그레이션(saas_company_accounts.sql, saas_readonly_when_expired.sql)을 PGlite(메모리 Postgres)에 돌려 본다.
//  · 두 번 실행 안전  · is_company_active() 가 JS 쪽 subscriptionState 와 같은 답  · PIN 검증·잠금·권한
//  · 요금제 칸은 브라우저(auth.uid() 있음)가 못 바꾼다  · 만료 회사는 쓰기만 막히고 읽기는 된다
import { PGlite } from "@electric-sql/pglite";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SQL1 = fs.readFileSync(path.join(ROOT, "migrations/saas_company_accounts.sql"), "utf8");
const SQL2 = fs.readFileSync(path.join(ROOT, "migrations/saas_readonly_when_expired.sql"), "utf8");
const sub = await import(pathToFileURL(path.join(ROOT, "src/saas/lib/subscription.js")).href);

const U1 = "11111111-1111-1111-1111-111111111111";   // 체험 중
const U2 = "22222222-2222-2222-2222-222222222222";   // 행 없음(사내 계정)
const U3 = "33333333-3333-3333-3333-333333333333";   // 체험 끝

const results = [];
const check = (name, ok, detail = "") => { results.push(!!ok); console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? "  — " + detail : ""}`); };
const q = async (sql, params) => (await db.query(sql, params)).rows;
const fails = async (sql, params) => { try { if (params) await db.query(sql, params); else await db.exec(sql); return null; } catch (e) { return e.message; } };

const db = new PGlite({ extensions: { pgcrypto } });
await db.exec(`
  create schema auth;
  create table auth.users (id uuid primary key);
  insert into auth.users values ('${U1}'), ('${U2}'), ('${U3}');
  create function auth.uid() returns uuid language sql stable as $$
    select nullif(current_setting('test.uid', true), '')::uuid
  $$;
  create role authenticated; create role anon; create role service_role;
  create table managers (id bigint generated by default as identity primary key, user_id uuid, name text, is_admin boolean default false, is_public boolean default false, is_packer boolean default false);
  create table orders (id uuid primary key default gen_random_uuid(), user_id uuid, customer text, status text default '접수');
  alter table managers enable row level security; alter table orders enable row level security;
  create policy tenant_managers on managers for all using (user_id = auth.uid()) with check (user_id = auth.uid());
  create policy tenant_orders on orders for all using (user_id = auth.uid()) with check (user_id = auth.uid());
  insert into managers (user_id, name, is_admin) values ('${U1}', '사장', true), ('${U1}', '직원', false), ('${U1}', '방문고객', false), ('${U3}', '만료사장', true);
  update managers set is_public = true where name = '방문고객';
  insert into orders (user_id, customer) values ('${U1}', '김영희'), ('${U3}', '박철수');
`);

// ── 1. 실행·재실행 ──
let e1 = await fails(SQL1); check("1a. company_accounts 마이그레이션 실행", !e1, e1);
let e2 = await fails(SQL1); check("1b. 재실행 안전", !e2, e2);
let e3 = await fails(SQL2); check("1c. 읽기 전용 정책 실행", !e3, e3);
let e4 = await fails(SQL2); check("1d. 재실행 안전", !e4, e4);
const pol = await q(`select tablename, policyname, permissive from pg_policies where policyname like 'saas_active_%' order by 1,2`);
check("1e. 있는 표(orders·managers)에만 제한 정책 3개씩, 없는 표는 건너뜀", pol.length === 6 && pol.every(p => p.permissive === "RESTRICTIVE"), pol.map(p => p.tablename + "." + p.policyname).join(","));

// ── 2. 회사 계정 + 활성 판정 (JS 와 같은 답) ──
await db.exec(`
  insert into company_accounts (owner_id, login_id, name, plan, trial_end) values ('${U1}', 'rohi', '로하이마켓', 'trial', now() + interval '10 days') on conflict do nothing;
  insert into company_accounts (owner_id, login_id, name, plan, trial_end) values ('${U3}', 'ended', '끝난회사', 'trial', now() - interval '1 day') on conflict do nothing;
`);
check("2a. 아이디 형식 검사(대문자 거부)", !!(await fails(`insert into company_accounts (owner_id, login_id) values ('${U2}', 'Bad')`)));
const active = async (uid) => { await db.exec(`set test.uid = '${uid}'`); return (await q(`select is_company_active() a`))[0].a; };
check("2b. 체험 중 → 활성", await active(U1) === true);
check("2c. 행 없음 → 활성", await active(U2) === true);
check("2d. 체험 끝 → 비활성", await active(U3) === false);
// JS 와 SQL 을 같은 사례로 비교
const cases = [
  { plan: "basic", status: "active", period: "+20 days", want: true },
  { plan: "pro", status: "active", period: "-2 days", want: true },      // 유예 안
  { plan: "pro", status: "active", period: "-4 days", want: false },     // 유예 지남
  { plan: "basic", status: "active", period: null, want: true },         // 기간 없음(수동)
  { plan: "pro", status: "canceled", period: "+20 days", want: false },
  { plan: "basic", status: "past_due", period: "-1 days", want: true },
];
let agree = true;
for (const c of cases) {
  await db.exec(`set test.uid = ''`);
  await db.query(`update company_accounts set plan=$1, status=$2, current_period_end = ${c.period ? `now() + interval '${c.period}'` : "null"} where owner_id=$3`, [c.plan, c.status, U3]);
  const sqlA = await active(U3);
  const row = (await q(`select * from company_accounts where owner_id=$1`, [U3]))[0];
  const jsA = sub.subscriptionState(row, new Date()).active;
  if (sqlA !== c.want || jsA !== c.want) { agree = false; console.log("   불일치", c, { sqlA, jsA }); }
}
check("2e. 유료·유예·해지 6사례 — SQL 과 JS 가 같은 답", agree);
await db.exec(`set test.uid = ''`);
await db.query(`update company_accounts set plan='trial', status='active', current_period_end=null, trial_end = now() - interval '1 day' where owner_id=$1`, [U3]);

// 요금제 보호 트리거
await db.exec(`set test.uid = '${U1}'`);
check("2f. 브라우저는 회사명·연락처 변경 가능", !(await fails(`update company_accounts set name='로하이마켓(주)', contact='010' where owner_id='${U1}'`)));
check("2g. 브라우저는 요금제 변경 불가", !!(await fails(`update company_accounts set plan='pro' where owner_id='${U1}'`)));
check("2h. 브라우저는 기간 변경 불가", !!(await fails(`update company_accounts set trial_end = now() + interval '1 year' where owner_id='${U1}'`)));
await db.exec(`set test.uid = ''`);
check("2i. 서버(service role, uid 없음)는 요금제 변경 가능", !(await fails(`update company_accounts set plan='pro', current_period_end = now() + interval '30 days' where owner_id='${U1}'`)));
await db.query(`update company_accounts set plan='trial', current_period_end=null where owner_id=$1`, [U1]);

// ── 3. PIN ──
await db.exec(`set test.uid = '${U1}'`);
const ids = Object.fromEntries((await q(`select id, name from managers where user_id='${U1}'`)).map(r => [r.name, r.id]));
const rpc = async (sql, params) => (await q(sql, params))[0].r;
let st = await rpc(`select manager_pin_status() r`);
check("3a. 상태: 담당자 3명, 아직 PIN 없음", st.length === 3 && st.every(x => x.has_pin === false), JSON.stringify(st));
let v = await rpc(`select verify_manager_pin($1, '1234') r`, [ids["사장"]]);
check("3b. PIN 없는 담당자 검증 → no_pin", v.ok === false && v.no_pin === true);
let r = await rpc(`select set_manager_pin($1, '12a4') r`, [ids["사장"]]);
check("3c. 숫자 4자리 아니면 거부", r.ok === false);
r = await rpc(`select set_manager_pin($1, '1234') r`, [ids["사장"]]);
check("3d. 처음 PIN 은 증명 없이 설정(온보딩)", r.ok === true, JSON.stringify(r));
r = await rpc(`select set_manager_pin($1, '0000') r`, [ids["직원"]]);
check("3e. 직원도 처음 PIN 설정", r.ok === true);
v = await rpc(`select verify_manager_pin($1, '1234') r`, [ids["사장"]]);
check("3f. 맞는 PIN → ok", v.ok === true);
v = await rpc(`select verify_manager_pin($1, '9999') r`, [ids["사장"]]);
check("3g. 틀린 PIN → attempts_left 4", v.ok === false && v.attempts_left === 4, JSON.stringify(v));
r = await rpc(`select set_manager_pin($1, '5678') r`, [ids["사장"]]);
check("3h. 이미 있는 PIN 은 증명 없이 못 바꿈", r.ok === false);
r = await rpc(`select set_manager_pin($1, '5678', $1, '9999') r`, [ids["사장"]]);
check("3i. 현재 PIN 틀리면 못 바꿈", r.ok === false);
r = await rpc(`select set_manager_pin($1, '5678', $1, '1234') r`, [ids["사장"]]);
check("3j. 본인이 현재 PIN 맞추면 변경", r.ok === true, JSON.stringify(r));
v = await rpc(`select verify_manager_pin($1, '5678') r`, [ids["사장"]]);
check("3k. 바뀐 PIN 으로 통과, 실패 횟수 초기화", v.ok === true);
r = await rpc(`select set_manager_pin($1, '1111', $2, '0000') r`, [ids["사장"], ids["직원"]]);
check("3l. 직원(비관리자)은 사장 PIN 못 바꿈", r.ok === false && /관리자/.test(r.error), r.error);
r = await rpc(`select set_manager_pin($1, '1111', $2, '5678') r`, [ids["직원"], ids["사장"]]);
check("3m. 관리자는 직원 PIN 변경", r.ok === true);
// 잠금: 5회 실패
for (let i = 0; i < 4; i++) v = await rpc(`select verify_manager_pin($1, '0000') r`, [ids["직원"]]);
check("3n. 4회 실패 → attempts_left 1", v.attempts_left === 1, JSON.stringify(v));
v = await rpc(`select verify_manager_pin($1, '0000') r`, [ids["직원"]]);
check("3o. 5회 실패 → locked_until", v.ok === false && !!v.locked_until);
v = await rpc(`select verify_manager_pin($1, '1111') r`, [ids["직원"]]);
check("3p. 잠긴 동안은 맞는 PIN 도 거부", v.ok === false && !!v.locked_until);
st = await rpc(`select manager_pin_status() r`);
check("3q. 상태에 locked_until 노출, 해시는 노출 안 됨", st.find(x => x.manager_id === ids["직원"]).locked_until && !JSON.stringify(st).includes("pin_hash"));
check("3r. 브라우저는 manager_pins 를 직접 못 읽음(정책 없음)", (await q(`select count(*)::int n from pg_policies where tablename='manager_pins'`))[0].n === 0);
// 다른 회사 담당자
await db.exec(`set test.uid = '${U3}'`);
v = await rpc(`select verify_manager_pin($1, '5678') r`, [ids["사장"]]);
check("3s. 다른 회사의 담당자 PIN 은 검증 불가", v.ok === false && /찾을 수 없/.test(v.error));
// 서버 전용 리셋
r = await rpc(`select service_reset_manager_pin($1, $2, '2222') r`, [U1, ids["직원"]]);
check("3t. 브라우저(uid 있음)는 서버 리셋 함수 못 씀", r.ok === false);
await db.exec(`set test.uid = ''`);
r = await rpc(`select service_reset_manager_pin($1, $2, '2222') r`, [U1, ids["직원"]]);
await db.exec(`set test.uid = '${U1}'`);
v = await rpc(`select verify_manager_pin($1, '2222') r`, [ids["직원"]]);
check("3u. 서버 리셋 → 잠금 풀리고 새 PIN 통과", r.ok === true && v.ok === true, JSON.stringify({ r, v }));

// ── 4. 만료 회사는 읽기 전용 (authenticated 역할로 RLS 적용) ──
await db.exec(`grant usage on schema public to authenticated; grant all on all tables in schema public to authenticated; grant usage, select on all sequences in schema public to authenticated;`);
await db.exec(`set role authenticated; set test.uid = '${U3}'`);
check("4a. 만료 회사도 읽기는 됨", (await q(`select count(*)::int n from orders`))[0].n === 1);
let ins = await fails(`insert into orders (user_id, customer) values ('${U3}', '새주문')`);
check("4b. 만료 회사 insert 차단", !!ins, ins);
const upd = (await q(`update orders set status='포장완료' where user_id='${U3}' returning id`)).length;
check("4c. 만료 회사 update 는 0행", upd === 0);
await db.exec(`set test.uid = '${U1}'`);
ins = await fails(`insert into orders (user_id, customer) values ('${U1}', '새주문')`);
check("4d. 체험 중 회사는 insert 가능", !ins, ins);
await db.exec(`set test.uid = '${U2}'`);
ins = await fails(`insert into orders (user_id, customer) values ('${U2}', '사내주문')`);
check("4e. 행 없는 회사(사내 계정)도 그대로 가능", !ins, ins);
await db.exec(`reset role`);

const failed = results.filter(x => !x).length;
console.log(`\n${results.length - failed}/${results.length} 통과`);
process.exit(failed ? 1 : 0);
