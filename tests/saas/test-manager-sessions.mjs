// 담당자 토큰(saas_manager_sessions.sql) — PIN 통과 → 토큰, 헤더의 토큰 → 담당자, 관리자 전용 정책·트리거.
import { PGlite } from "@electric-sql/pglite";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SQL1 = fs.readFileSync(path.join(ROOT, "migrations/saas_company_accounts.sql"), "utf8");
const SQL2 = fs.readFileSync(path.join(ROOT, "migrations/saas_manager_sessions.sql"), "utf8");
const U1 = "11111111-1111-1111-1111-111111111111";
const U2 = "22222222-2222-2222-2222-222222222222";

const results = [];
const check = (name, ok, detail = "") => { results.push(!!ok); console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? "  — " + detail : ""}`); };
const q = async (sql, params) => (await db.query(sql, params)).rows;
const fails = async (sql, params) => { try { if (params) await db.query(sql, params); else await db.exec(sql); return null; } catch (e) { return e.message; } };
const headers = async (tok) => db.exec(`set request.headers = '${tok === null ? "{}" : JSON.stringify({ "x-manager-token": tok })}'`);

const db = new PGlite({ extensions: { pgcrypto } });
await db.exec(`
  create schema auth;
  create table auth.users (id uuid primary key);
  insert into auth.users values ('${U1}'), ('${U2}');
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid', true), '')::uuid $$;
  create role authenticated; create role anon; create role service_role;
  create table managers (id bigint generated by default as identity primary key, user_id uuid, name text, is_admin boolean default false, is_public boolean default false, is_packer boolean default false);
  create table orders (id uuid primary key default gen_random_uuid(), user_id uuid, customer text, status text default '접수');
  create table products (id bigint generated by default as identity primary key, user_id uuid, code text);
  alter table managers enable row level security; alter table orders enable row level security; alter table products enable row level security;
  create policy tenant_managers on managers for all using (user_id = auth.uid()) with check (user_id = auth.uid());
  create policy tenant_orders on orders for all using (user_id = auth.uid()) with check (user_id = auth.uid());
  create policy tenant_products on products for all using (user_id = auth.uid()) with check (user_id = auth.uid());
  insert into managers (user_id, name, is_admin) values ('${U1}', '사장', true), ('${U1}', '직원', false), ('${U2}', '남의사장', true);
  insert into orders (user_id, customer) values ('${U1}', '김영희'), ('${U1}', '박철수');
  grant usage on schema public to authenticated; grant all on all tables in schema public to authenticated; grant usage, select on all sequences in schema public to authenticated;
`);

let e = await fails(SQL1); check("0a. company_accounts 실행", !e, e);
e = await fails(SQL2); check("0b. manager_sessions 실행", !e, e);
e = await fails(SQL2); check("0c. 재실행 안전", !e, e);
await db.exec(`grant all on all tables in schema public to authenticated; grant usage, select on all sequences in schema public to authenticated;`);

await db.exec(`set test.uid = '${U1}'`);
const ids = Object.fromEntries((await q(`select id, name from managers where user_id='${U1}'`)).map(r => [r.name, r.id]));
await q(`select set_manager_pin($1, '1234') r`, [ids["사장"]]);
await q(`select set_manager_pin($1, '0000') r`, [ids["직원"]]);

// ── 1. 토큰 발급 ──
let v = (await q(`select verify_manager_pin($1, '9999') r`, [ids["사장"]]))[0].r;
check("1a. 틀린 PIN 은 토큰 없음", v.ok === false && !v.token);
v = (await q(`select verify_manager_pin($1, '1234') r`, [ids["사장"]]))[0].r;
const adminTok = v.token;
check("1b. 맞는 PIN → 48자 hex 토큰", v.ok === true && /^[0-9a-f]{48}$/.test(adminTok || ""), JSON.stringify(v).slice(0, 80));
const staffTok = (await q(`select verify_manager_pin($1, '0000') r`, [ids["직원"]]))[0].r.token;
check("1c. 직원 토큰도 발급", /^[0-9a-f]{48}$/.test(staffTok || ""));
const stored = (await q(`select token_hash from manager_sessions where manager_id=$1`, [ids["사장"]]))[0].token_hash;
check("1d. DB 에는 해시만(토큰 원문 아님)", stored !== adminTok && stored.length === 64);

// ── 2. 헤더 → 담당자 ──
await headers(null);
check("2a. 헤더 없으면 담당자 없음·관리자 아님", (await q(`select current_manager_id() m, current_manager_is_admin() a`))[0].m === null && (await q(`select current_manager_is_admin() a`))[0].a === false);
await headers("deadbeef");
check("2b. 엉뚱한 토큰 → 없음", (await q(`select current_manager_id() m`))[0].m === null);
await headers(adminTok);
check("2c. 관리자 토큰 → 사장, admin=true", (await q(`select current_manager_id() m`))[0].m === ids["사장"] && (await q(`select current_manager_is_admin() a`))[0].a === true);
await headers(staffTok);
check("2d. 직원 토큰 → 직원, admin=false", (await q(`select current_manager_id() m`))[0].m === ids["직원"] && (await q(`select current_manager_is_admin() a`))[0].a === false);
await db.exec(`set test.uid = '${U2}'`); await headers(adminTok);
check("2e. 다른 회사 세션에서 쓰면 무효", (await q(`select current_manager_id() m`))[0].m === null);
await db.exec(`set test.uid = '${U1}'`);

// ── 3. 관리자 전용 (RLS 는 authenticated 역할로) ──
await db.exec(`set role authenticated; set test.uid = '${U1}'`);
await headers(staffTok);
let n = (await q(`delete from orders where customer='김영희' returning id`)).length;
check("3a. 직원은 주문 삭제 0행", n === 0);
let err = await fails(`insert into managers (user_id, name) values ('${U1}', '새담당')`);
check("3b. 직원은 담당자 추가 불가", !!err, err);
err = await fails(`update orders set status='출고완료' where customer='박철수'`);
check("3c. 직원은 출고완료 전환 불가(트리거)", /관리자/.test(err || ""), err);
err = await fails(`update orders set status='포장완료' where customer='박철수'`);
check("3d. 직원도 포장완료는 가능", !err, err);
await headers(adminTok);
n = (await q(`delete from orders where customer='김영희' returning id`)).length;
check("3e. 관리자는 주문 삭제", n === 1);
err = await fails(`insert into managers (user_id, name) values ('${U1}', '새담당')`);
check("3f. 관리자는 담당자 추가", !err, err);
err = await fails(`update orders set status='출고완료' where customer='박철수'`);
check("3g. 관리자는 출고완료 전환", !err, err);
await headers(null);
err = await fails(`update orders set status='접수' where customer='박철수'`);
check("3h. 토큰 없어도 일반 상태 변경은 가능(기존 동작 유지)", !err, err);
await db.exec(`reset role`);

// ── 4. 서버(service role, uid 없음)는 제한 없음 ──
await db.exec(`set test.uid = ''`); await headers(null);
err = await fails(`update orders set status='출고완료' where customer='박철수'`);
check("4a. 서버는 출고완료 트리거를 거치지 않음", !err, err);
await db.exec(`set test.uid = '${U1}'`);

// ── 5. 구독 만료 트리거(롤·포장 표) ──
await db.exec(`insert into company_accounts (owner_id, login_id, name, plan, trial_end) values ('${U1}', 'comp1', '회사', 'trial', now() + interval '1 day') on conflict do nothing`);
err = await fails(`insert into products (user_id, code) values ('${U1}', 'A-1')`);
check("5a. 체험 중엔 products 쓰기 가능", !err, err);
await db.exec(`set test.uid = ''`); await db.query(`update company_accounts set trial_end = now() - interval '1 day' where owner_id=$1`, [U1]); await db.exec(`set test.uid = '${U1}'`);
err = await fails(`insert into products (user_id, code) values ('${U1}', 'A-2')`);
check("5b. 만료되면 products 쓰기 차단(RPC 도 거치는 트리거)", /읽기 전용/.test(err || ""), err);

// ── 6. 토큰 폐기 ──
await headers(adminTok);
await q(`select revoke_manager_token()`);
check("6. revoke 뒤 같은 토큰은 무효", (await q(`select current_manager_id() m`))[0].m === null);

const failed = results.filter(x => !x).length;
console.log(`\n${results.length - failed}/${results.length} 통과`);
process.exit(failed ? 1 : 0);
