for (const f of ["migrations/saas_company_accounts.sql", "migrations/saas_manager_sessions.sql", "migrations/saas_order_lock.sql"]) {
  const e = await fails(read(f)); check(`0. ${path.basename(f)} 실행`, !e, e);
}
check("0b. 재실행 안전", !(await fails(read("migrations/saas_order_lock.sql"))));
await db.exec(`grant all on all tables in schema public to authenticated;`);
await db.exec(`set test.uid = '${U1}'`);
