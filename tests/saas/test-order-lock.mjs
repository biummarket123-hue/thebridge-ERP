const managers = (await q(`select name, is_admin as "isAdmin", is_public as "isPublic", is_packer as "isPacker" from managers`));
const orders = (await q(`select customer, manager, merge_group_id as "mergeGroupId" from orders`));
const js = (who, customer) => lock.checkOrderLock(orders.find(o => o.customer === customer), who, managers, orders) === null;

// ── 직원A ──
