// 1단계 마이그레이션(add_stock_rolls.sql)을 진짜 Postgres(PGlite, 메모리)에 돌려 본다.
// 실행: npm test (tests/run.mjs 가 이 폴더의 test-*.mjs 를 차례로 돈다)
// Supabase 가 미리 만들어 두는 것(auth·storage 스키마, publication, 역할)은 흉내만 낸다.
import { PGlite } from "@electric-sql/pglite";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SQL = fs.readFileSync(path.join(ROOT, "migrations/add_stock_rolls.sql"), "utf8");
const U1 = "11111111-1111-1111-1111-111111111111";
const U2 = "22222222-2222-2222-2222-222222222222";

const results = [];
const check = (name, ok, detail = "") => {
  results.push({ name, ok });
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? "  — " + detail : ""}`);
};

const db = new PGlite();
await db.exec(`
  create schema auth;
  create table auth.users (id uuid primary key);
  insert into auth.users values ('${U1}'), ('${U2}');
  create function auth.uid() returns uuid language sql stable as $$
    select nullif(current_setting('test.uid', true), '')::uuid
  $$;
  create role authenticated;
  create schema storage;
  create table storage.buckets (id text primary key, name text, public boolean);
  create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text, name text);
  alter table storage.objects enable row level security;
  create publication supabase_realtime;
  create table inventory (
    id bigint generated by default as identity primary key,
    user_id uuid, fabric text not null, color text default '', stock numeric default 0,
    item_no text, unit_price numeric
  );
  insert into inventory (user_id, fabric, color, stock, item_no, unit_price) values
    ('${U1}', '린넨코튼', '베이지', 421, 'a-001', 5000),
    ('${U1}', '린넨코튼 중복', '', 10, ' A-001 ', 0),
    ('${U1}', '품번없음', '', 10, '', 3000),
    ('${U1}', '품번없음2', '', 10, null, 3000),
    ('${U1}', '쉬폰', null, 370, 'B-002', 0),
    ('${U2}', '다른회사', '', 5, 'A-001', 1000);
`);

// ── 기준 1: 두 번 실행해도 에러 없음 ──
let err1 = null, err2 = null;
try { await db.exec(SQL); } catch (e) { err1 = e; }
check("1a. 마이그레이션 1회차 실행", !err1, err1?.message);
const after1 = (await db.query("select count(*)::int n from products")).rows[0].n;
try { await db.exec(SQL); } catch (e) { err2 = e; }
check("1b. 마이그레이션 2회차 실행(재실행 안전)", !err2, err2?.message);
const after2 = (await db.query("select count(*)::int n from products")).rows[0].n;
check("1c. 재실행해도 품번이 늘지 않음", after1 === after2, `${after1} → ${after2}`);

// ── 2-5 품번 이식 ──
const imported = (await db.query("select user_id, code, name, color, unit_price from products order by user_id, code")).rows;
check("이식: item_no 있는 것만, 대문자·공백 제거, 중복은 한 번", imported.length === 3
  && imported.filter(r => r.user_id === U1).map(r => r.code).join(",") === "A-001,B-002",
  JSON.stringify(imported.map(r => [r.code, r.name, r.color, r.unit_price])));
check("이식: 단가 0 은 null, color null 은 ''", imported.find(r => r.code === "B-002").unit_price === null
  && imported.find(r => r.code === "B-002").color === "");
check("이식: 롤은 만들지 않음", (await db.query("select count(*)::int n from stock_rolls")).rows[0].n === 0);

// 정책·버킷·publication
const pol = (await db.query(`select tablename, policyname from pg_policies where policyname like 'tenant_%' or policyname like 'product-images%' order by 1,2`)).rows;
check("RLS 정책 3개 + 버킷 정책 3개", pol.length === 6, pol.map(p => p.policyname).join(", "));
const pub = (await db.query(`select tablename from pg_publication_tables where pubname='supabase_realtime' order by 1`)).rows.map(r => r.tablename);
check("Realtime: products·stock_rolls 만 (stock_movements 제외)", pub.join(",") === "products,stock_rolls", pub.join(","));
check("버킷 product-images 1개", (await db.query("select count(*)::int n from storage.buckets where id='product-images'")).rows[0].n === 1);

// ── 기준 2: 품번 형식 ──
await db.exec(`set test.uid = '${U1}'`);
const code = (await db.query("select next_product_code() c")).rows[0].c;
const code2 = (await db.query("select next_product_code() c")).rows[0].c;
check("2. 품번 형식 LH-YYMM-####", /^LH-\d{4}-\d{4}$/.test(code) && code !== code2, `${code}, ${code2}`);
const prod = (await db.query(
  `insert into products (user_id, code, name, color) values ('${U1}', $1, '테스트 원단', '네이비') returning *`, [code])).rows[0];
check("2. products 에 1행", !!prod.id && prod.unit === "마");

// ── 기준 3: 롤 3개 ──
for (const n of ["01", "02", "03"]) {
  await db.query(`insert into stock_rolls (user_id, product_id, roll_code, length_received, supplier, location)
    values ('${U1}', $1, $2, 45, '동대문', 'A-03')`, [prod.id, `${code}-R${n}`]);
}
const rolls = (await db.query("select * from stock_rolls where product_id=$1 order by roll_code", [prod.id])).rows;
check("3. 롤 3행, status=received, R01~R03", rolls.length === 3 && rolls.every(r => r.status === "received")
  && rolls.map(r => r.roll_code.slice(-4)).join(",") === "-R01,-R02,-R03"
  && rolls.every(r => r.length_available === null && r.length_remaining === null));
let dup = null;
try { await db.query(`insert into stock_rolls (user_id, product_id, roll_code, length_received) values ('${U1}', $1, $2, 1)`, [prod.id, `${code}-R01`]); }
catch (e) { dup = e; }
check("3. 같은 roll_code 는 거부(23505)", dup?.code === "23505", dup?.code);

const R = rolls[0].id;
const mv = async () => (await db.query("select type, qty::float8 qty, note, created_by from stock_movements where roll_id=$1 order by id", [R])).rows;
const roll = async () => (await db.query(`select status, length_available::float8 la, length_remaining::float8 lr,
  inspected_at, inspected_by, label_requested_at, label_printed_at from stock_rolls where id=$1`, [R])).rows[0];
const rpc = (type, qty, note = null, by = "검단자") =>
  db.query("select * from roll_apply_movement($1, $2, $3, null, $4, $5)", [R, type, qty, note, by]);

// ── 기준 4: 검단 42.5 ──
await rpc("inspect", 42.5);
let r = await roll(), m = await mv();
check("4. inspect 1행(qty 42.5)", m.length === 1 && m[0].type === "inspect" && m[0].qty === 42.5);
check("4. status=available, 실측=잔량=42.5, 검단자 기록", r.status === "available" && r.la === 42.5 && r.lr === 42.5
  && !!r.inspected_at && r.inspected_by === "검단자");
// 라벨 요청은 화면(db.js requestRollLabelPrint)이 하는 UPDATE 다 — 같은 문장을 그대로 돌린다
await db.query("update stock_rolls set label_requested_at = now(), label_printed_at = null where id = $1 and user_id = $2", [R, U1]);
r = await roll();
check("4. label_requested_at 채워짐", !!r.label_requested_at && r.label_printed_at === null);

// ── 기준 5: 출력권은 한 대만 ──
const claim = () => db.query(
  "update stock_rolls set label_printed_at = now() where id = $1 and user_id = $2 and label_printed_at is null returning id", [R, U1]);
const c1 = await claim(), c2 = await claim();
check("5. 출력권 선점 — 첫 기기 1행, 둘째 기기 0행", c1.rows.length === 1 && c2.rows.length === 0);
check("5. label_printed_at 채워짐", !!(await roll()).label_printed_at);

// ── 기준 6: 재출력 ──
await db.query("update stock_rolls set label_requested_at = now(), label_printed_at = null where id = $1 and user_id = $2", [R, U1]);
check("6. 재출력 요청 → label_printed_at 이 null 로", (await roll()).label_printed_at === null);
const c3 = await claim();
check("6. 다시 1장 선점 가능", c3.rows.length === 1);

// ── 기준 7: 조정 -2.5 ──
await rpc("adjust", -2.5, "재단 실수");
r = await roll(); m = await mv();
check("7. 잔량 40, adjust 1행(qty -2.5)", r.lr === 40 && m.length === 2 && m[1].type === "adjust" && m[1].qty === -2.5
  && r.status === "available" && r.la === 42.5);

// ── 기준 8: 조정 -50 → 에러, 되돌림 ──
let e8 = null;
try { await rpc("adjust", -50, "잘못 입력"); } catch (e) { e8 = e; }
r = await roll(); m = await mv();
check("8. RPC 에러 'remaining below zero'", /remaining below zero/.test(e8?.message || ""), e8?.message);
check("8. 잔량 40 유지, 기록 추가 안 됨, status 그대로", r.lr === 40 && m.length === 2 && r.status === "available");

// ── 기준 9: 폐기 ──
await rpc("scrap", -40, "오염");
r = await roll(); m = await mv();
check("9. status=scrapped, 잔량 0, scrap 1행(qty -40)", r.status === "scrapped" && r.lr === 0
  && m.length === 3 && m[2].type === "scrap" && m[2].qty === -40);

// ── 그 밖의 경계 ──
// 검단에서 실측 0 → 전량 폐기 (검단 전 롤: 잔량 null)
const R2 = rolls[1].id;
await db.query("select * from roll_apply_movement($1, 'scrap', 0, null, '검단 전량 폐기', '검단자')", [R2]);
const r2 = (await db.query("select status, length_remaining::float8 lr from stock_rolls where id=$1", [R2])).rows[0];
check("검단 전 롤 전량 폐기 → scrapped, 잔량 0", r2.status === "scrapped" && r2.lr === 0);

// 다른 회사의 롤은 못 건드린다
await db.exec(`set test.uid = '${U2}'`);
let eX = null;
try { await db.query("select * from roll_apply_movement($1, 'adjust', -1, null, null, null)", [rolls[2].id]); } catch (e) { eX = e; }
check("다른 user_id 는 'roll not found'", /roll not found/.test(eX?.message || ""), eX?.message);
await db.exec(`set test.uid = '${U1}'`);

// 허용되지 않은 type
let eT = null;
try { await db.query("select * from roll_apply_movement($1, 'steal', -1, null, null, null)", [rolls[2].id]); } catch (e) { eT = e; }
check("모르는 type 은 거부(check 제약)", eT?.code === "23514", eT?.code);

// ── 상태 검사 (2026-09-30 보강) ──
const mkRoll = async (n) => (await db.query(`insert into stock_rolls (user_id, product_id, roll_code, length_received)
  values ('${U1}', $1, $2, 45) returning id`, [prod.id, `${code}-R${n}`])).rows[0].id;
const rollOf = async (id) => (await db.query(
  "select status, length_available::float8 la, length_remaining::float8 lr, inspected_by from stock_rolls where id=$1", [id])).rows[0];
const mvOf = async (id) => (await db.query("select type, qty::float8 qty from stock_movements where roll_id=$1 order by id", [id])).rows;
const rpcOn = (id, type, qty, note = null, by = "검단자") =>
  db.query("select * from roll_apply_movement($1, $2, $3, null, $4, $5)", [id, type, qty, note, by]);
const tryRpc = async (...a) => { try { await rpcOn(...a); return null; } catch (e) { return e; } };

// available 롤에 inspect 재전송 → 에러, 잔량 불변
const R4 = await mkRoll("04");
await rpcOn(R4, "inspect", 30);
await rpcOn(R4, "adjust", -12, "재단");
const eRe = await tryRpc(R4, "inspect", 30, null, "다른사람");
let r4 = await rollOf(R4), m4 = await mvOf(R4);
check("재검단: available 롤에 inspect 재전송 → '이미 검단된 롤' 에러", /이미 검단된 롤/.test(eRe?.message || "")
  && (eRe?.message || "").includes(`${code}-R04`), eRe?.message);
check("재검단: 잔량 18 불변, 실측 30 불변, 검단자 그대로, 기록 추가 안 됨",
  r4.lr === 18 && r4.la === 30 && r4.status === "available" && r4.inspected_by === "검단자" && m4.length === 2,
  JSON.stringify({ ...r4, movements: m4.length }));

// sold 롤에 +5 adjust → available, 잔량 5
const R5 = await mkRoll("05");
await rpcOn(R5, "inspect", 10);
await rpcOn(R5, "adjust", -10, "다 나감");
let r5 = await rollOf(R5);
check("sold 준비: 잔량 0 이 되면 status=sold", r5.status === "sold" && r5.lr === 0, JSON.stringify(r5));
const eUp = await tryRpc(R5, "adjust", 5, "창고에서 5마 발견");
r5 = await rollOf(R5);
check("sold 롤에 +5 adjust → available, 잔량 5", !eUp && r5.status === "available" && r5.lr === 5,
  eUp?.message || JSON.stringify(r5));

// sold 롤: adjust 만 열려 있다
const eCut = await tryRpc(R5, "adjust", -5, "다시 다 나감");
r5 = await rollOf(R5);
check("되살린 롤을 다시 0 으로 → sold", !eCut && r5.status === "sold" && r5.lr === 0, eCut?.message || JSON.stringify(r5));
const eSoldCut = await tryRpc(R5, "cut", -1);
check("sold 롤에 cut → '판매 가능 상태가 아닌 롤' 에러", /판매 가능 상태가 아닌 롤.*sold/.test(eSoldCut?.message || ""), eSoldCut?.message);
const eSoldNeg = await tryRpc(R5, "adjust", -1);
check("sold 롤에 -1 adjust → 'remaining below zero', 잔량 0 그대로",
  /remaining below zero/.test(eSoldNeg?.message || "") && (await rollOf(R5)).lr === 0, eSoldNeg?.message);

// 상태 검사의 나머지 경계
const R6 = await mkRoll("06");
const eRecv = await tryRpc(R6, "adjust", -1);
check("검단 전(received) 롤에 adjust → '판매 가능 상태가 아닌 롤' 에러, 기록 없음",
  /판매 가능 상태가 아닌 롤.*received/.test(eRecv?.message || "") && (await mvOf(R6)).length === 0, eRecv?.message);
const eScr = await tryRpc(R, "adjust", 3);   // R 은 기준 9 에서 폐기됨
check("폐기된(scrapped) 롤에 adjust → 에러, 잔량 0 그대로",
  /판매 가능 상태가 아닌 롤.*scrapped/.test(eScr?.message || "") && (await roll()).lr === 0 && (await roll()).status === "scrapped", eScr?.message);
const eScrIns = await tryRpc(R, "inspect", 40);
check("폐기된 롤에 inspect → '이미 검단된 롤' 에러", /이미 검단된 롤/.test(eScrIns?.message || ""), eScrIns?.message);
await rpcOn(R4, "scrap", -18, "오염");
r4 = await rollOf(R4);
check("scrap 은 available 에서도 그대로 동작 → scrapped, 잔량 0", r4.status === "scrapped" && r4.lr === 0, JSON.stringify(r4));

const failed = results.filter(x => !x.ok);
console.log(`\n${results.length - failed.length}/${results.length} 통과`);
process.exit(failed.length ? 1 : 0);
